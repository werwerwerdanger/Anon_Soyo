#!/usr/bin/env python3
"""Stage 3: settle the contradictions.

Stage 2 (test_engines.py) produced results that disagree with earlier
measurements, and it also had a self-inflicted flaw: the probe config dropped
bing's 'cn.bing.com' override, so bing fell back to www.bing.com and showed up
as "silent" -- which proves the 'silent' column cannot be read at face value.

This script fixes all of that:

  * keeps the REAL deployment settings as the base, so per-engine tuning
    (bing -> cn.bing.com) survives, and the probe is measuring the engine
    rather than the absence of a base_url
  * dumps /config so "was it even registered / selected?" is answered by the
    instance itself instead of inferred
  * runs the SAME query three times -- the 360search lesson was that an engine
    can answer once and then silently return nothing, and counting results
    across two DIFFERENT queries cannot detect that
  * prints the top result titles per engine, because a count says nothing about
    relevance: an engine can return 20 results that are all spam

Output is a report on stdout; the deployment config is restored on exit.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DEPLOY = os.path.normpath(os.path.join(HERE, '..', 'searxng-deploy'))
CONFIG = os.path.join(DEPLOY, 'config')
SETTINGS = os.path.join(CONFIG, 'settings.yml')
LIVE_LOCAL = os.path.join(DEPLOY, 'settings.local.yml')
BACKUP = SETTINGS + '.probe3-backup'
COMPOSE = 'docker-compose.local.yml'
BASE = 'http://127.0.0.1:8888'

# Every one of these returned results in stage 2, so each needs verification.
# bing is included as the known-good control: if bing looks wrong here, the
# harness is wrong, not the engine.
SUSPECTS = [
    'bing',           # control -- known good
    'yandex',
    'sogou',
    'sogou wechat',
    'naver',
    'baidu kaifa',
    'artic',
    'bilibili',
    'iqiyi',
    'acfun',
    'quark',
    '360search',
]

# The three-peat query. Chinese, because that is the real workload, and long
# enough to be a genuine relevance test rather than a keyword lookup.
QUERY = '成都理工大学 2026 年招生简章'


def run(cmd, merge=False, **kw):
    if merge:
        return subprocess.run(cmd, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, text=True, **kw)
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def no_proxy_urlopen(url, timeout=90):
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    return opener.open(url, timeout=timeout)


def wait_ready(deadline):
    while time.time() < deadline:
        try:
            with no_proxy_urlopen(BASE + '/healthz', timeout=3) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            pass
        time.sleep(1)
    return False


def fetch_json(path, timeout=120):
    with no_proxy_urlopen(BASE + path, timeout=timeout) as resp:
        return json.loads(resp.read().decode('utf-8'))


HEAD = '''# THROWAWAY probe config -- generated by test_engines2.py, restored on exit.
use_default_settings:
  engines:
    keep_only:
{keep}

engines:
{blocks}

server:
  secret_key: "{secret}"
  limiter: false
  image_proxy: false

search:
  safe_search: 1
  autocomplete: ""
  formats:
    - html
    - json
  max_page: 1

ui:
  static_use_hash: true

outgoing:
  request_timeout: 12.0
  max_request_timeout: 15.0
'''


def build_settings(base_text, names, secret='probe-secret'):
    """Build the probe config from scratch.

    Deliberately NOT regex surgery on the live file: an earlier attempt at
    grafting a new engine list into the existing YAML silently swallowed the
    server:/search:/ui: sections (a greedy DOTALL match), which would have made
    the whole measurement meaningless.  Building the file outright keeps every
    section accounted for, and the per-engine tuning that matters (bing ->
    cn.bing.com -- without it bing falls back to www.bing.com and turns into a
    false "silent" entry) is carried over explicitly.
    """
    keep = '\n'.join('      - %s' % n for n in names)
    blocks = []
    for n in names:
        b = ['  - name: %s' % n,
             '    disabled: false',
             # one shared category so a single plain query fires them all
             '    categories: [general]',
             '    timeout: 12.0']
        if n == 'bing':
            b.insert(2, '    base_url: https://cn.bing.com')
        blocks.append('\n'.join(b))
    return HEAD.format(keep=keep, blocks='\n\n'.join(blocks), secret=secret)


def main():
    base_text = open(LIVE_LOCAL, encoding='utf-8').read()
    secret = 'probe-secret'
    m = re.search(r'^  secret_key: (?:"|")?(.*?)"?$', base_text, re.M)
    if m:
        secret = m.group(1).strip().strip('"')

    probe = build_settings(base_text, SUSPECTS, secret)

    print('=' * 74)
    print('ENGINE HUNT -- stage 3: repeatability + relevance verification')
    print('=' * 74)
    print('suspects: %s' % ', '.join(SUSPECTS))
    print('query   : %s   (x3, identical)' % QUERY)
    print()

    shutil.copy2(SETTINGS, BACKUP)
    try:
        with open(SETTINGS, 'w', encoding='utf-8', newline='\n') as f:
            f.write(probe)

        out = run(['docker', 'compose', '-f', COMPOSE, 'up', '-d', '--force-recreate'],
                  cwd=DEPLOY)
        if out.returncode != 0:
            print(out.stdout[-1500:])
            print(out.stderr[-1500:])
            sys.exit('compose failed')

        if not wait_ready(time.time() + 60):
            sys.exit('container never became ready')

        # ---- what did the instance actually register? ----
        try:
            cfg = fetch_json('/config')
        except Exception as exc:
            sys.exit('could not read /config: %s' % exc)

        print('--- /config: engines the instance actually registered')
        seen = set()
        for eng in cfg.get('engines', []):
            nm = eng.get('name')
            seen.add(nm)
            flag = '' if eng.get('enabled', True) else '  [DISABLED]'
            print('    %-22s %-16s %s%s' % (nm, ','.join(eng.get('categories', [])),
                                            'selected' if eng.get('enabled', True)
                                            else 'off', flag))
        missing = [n for n in SUSPECTS if n not in seen]
        print('    registered: %d/%d' % (len(SUSPECTS) - len(missing), len(SUSPECTS)))
        if missing:
            print('    !! NOT REGISTERED: %s' % ', '.join(missing))
        print()

        # ---- three identical requests ----
        runs = []
        for i in range(1, 4):
            try:
                body = fetch_json('/search?q=' + urllib.parse.quote(QUERY) + '&format=json')
            except Exception as exc:
                print('--- run %d: REQUEST FAILED %s' % (i, exc))
                runs.append({})
                continue
            counts, samples = {}, {}
            for r in body.get('results', []):
                for e in r.get('engines', []) or ['?']:
                    counts[e] = counts.get(e, 0) + 1
                    samples.setdefault(e, []).append(r.get('title', '')[:70])
            unresp = dict((p[0], p[1]) for p in body.get('unresponsive_engines', [])
                          if isinstance(p, (list, tuple)) and len(p) == 2)
            runs.append({'counts': counts, 'samples': samples, 'unresp': unresp})
            print('--- run %d: %d results total' % (i, len(body.get('results', []))))
        print()

        print('=' * 74)
        print('PER-ENGINE VERDICT')
        print('=' * 74)
        for name in SUSPECTS:
            seq = [r.get('counts', {}).get(name, 0) for r in runs]
            err = [r.get('unresp', {}).get(name) for r in runs]
            err = [e for e in err if e]
            stable = len(set(seq)) == 1 and seq[0] > 0
            if seq[0] > 0 and stable:
                verdict = 'USABLE'
            elif seq[0] > 0:
                # answered at least once but not consistently -- the exact thing
                # this whole exercise is designed to catch
                verdict = 'FLAKY -- dropped values %s' % seq
            elif err:
                verdict = 'FAIL -- %s' % err[-1]
            else:
                verdict = 'SILENT -- selected but 0 results, no error reported'

            print()
            print('  %-16s %s' % (name, verdict))
            print('    result counts over 3 identical runs: %s' % seq)
            if err:
                print('    errors: %s' % err)
            # titles let me judge relevance instead of trusting the count
            titles = []
            for r in runs:
                for t in r.get('samples', {}).get(name, []):
                    if t not in titles:
                        titles.append(t)
            for t in titles[:3]:
                print('      - %s' % t)
    finally:
        print()
        print('--> restoring the real settings.yml')
        shutil.move(BACKUP, SETTINGS)
        out = run(['docker', 'compose', '-f', COMPOSE, 'up', '-d', '--force-recreate'],
                  cwd=DEPLOY)
        if out.returncode == 0:
            wait_ready(time.time() + 60)
            print('--> deployment restored and running at %s' % BASE)


if __name__ == '__main__':
    main()
