#!/usr/bin/env python3
"""Second-stage engine hunt: hand the candidate list to SearXNG itself.

The TCP screen in probe_reach_in_container.py was only a cheap pre-filter and
it had false negatives: generic engines ('xpath' / 'json_engine') keep their
address in settings.yml, not in Python, so scraping module source reported
"NO-BASE-URL" for engines that may be perfectly fine.

This script is authoritative instead.  It:
  1. validates every candidate name against the image's real engine list
     (a typo in keep_only makes SearXNG refuse to boot -- learned the hard way)
  2. writes a throwaway settings.yml enabling exactly those engines
  3. force-recreates the container so the new settings are actually read
  4. runs the same query twice, because 360search taught us that an engine can
     answer once and then silently return nothing for the next hour
  5. reports, per engine, the result count and the failure reason
  6. restores the real settings.yml and recreates the container again

Nothing here is left behind: the deployment config is byte-identical on exit.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DEPLOY = os.path.normpath(os.path.join(HERE, '..', 'searxng-deploy'))
CONFIG = os.path.join(DEPLOY, 'config')
SETTINGS = os.path.join(CONFIG, 'settings.yml')
BACKUP = SETTINGS + '.probe-backup'
COMPOSE = 'docker-compose.local.yml'
BASE = 'http://127.0.0.1:8888'

# Answers the question "which search engine should a QQ bot talk to?"
# Chinese first -- that is the real workload -- then the general/metasearch
# engines that could plausibly reach mainland China.
CANDIDATES = [
    # baseline: we already know how these behave
    'bing', 'baidu',
    # mainland Chinese
    'baidu kaifa', 'sogou', 'sogou wechat', '360search', 'quark',
    'chinaso news', 'sina', 'bilibili', 'acfun', 'iqiyi',
    # metasearch / aggregators
    'dogpile', 'metacrawler', 'zapmeta', 'fireball', 'privacywall',
    'tusksearch', 'startpagina', 'xprivo', 'vuhuv', 'luxxle', 'searchzee',
    # independent indexes
    'mojeek', 'marginalia', 'wiby', 'yacy', 'mwmbl', 'gabanza', 'cl0q',
    'artic', 'kukei', 'littlelayer', 'seekninja', 'unobtanium', 'neosearch',
    'resulthunter', 'zoo search', 's1search', 'searchmysite', 'searchrockit',
    'rawweb', 'findborg', 'iseek', 'mozhi', 'yep', 'boardreader',
    'crowdview', 'encyclosearch', 'xonaly',
    # the usual internationals, measured rather than assumed
    'duckduckgo', 'google', 'startpage', 'brave', 'qwant', 'yandex', 'yahoo',
    'naver', 'seznam', 'swisscows',
]

QUERIES = ['成都理工大学 2026 年招生', 'searxng engine reachability test']


def run(cmd, merge=False, **kw):
    """subprocess.run wrapper. merge=True folds stderr into stdout."""
    if merge:
        return subprocess.run(cmd, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, text=True, **kw)
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def image_engine_names():
    """The image's authoritative name list, straight out of its settings.yml."""
    py = (
        "import re,sys;"
        "t=open('/usr/local/searxng/searx/settings.yml',encoding='utf-8').read();"
        "print('\\n'.join(m.group(1).strip().strip(chr(34)).strip(chr(39))"
        " for m in re.finditer(r'(?m)^  - name: (.*)$', t)))"
    )
    out = run(['docker', 'exec', 'searxng', '/usr/bin/python3', '-c', py])
    if out.returncode != 0:
        print(out.stderr[:400])
        sys.exit('could not list engines')
    return set(n for n in out.stdout.split('\n') if n.strip())


def no_proxy_urlopen(url, timeout=90):
    """The sandbox forces outbound HTTP through a proxy; localhost must not be."""
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    return opener.open(url, timeout=timeout)


def wait_ready(deadline):
    while time.time() < deadline:
        try:
            with no_proxy_urlopen(BASE + '/healthz', timeout=3) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            pass
        time.sleep(1)
    return False


def query(q, timeout=90):
    url = BASE + '/search?q=' + urllib.parse.quote(q) + '&format=json'
    t0 = time.time()
    with no_proxy_urlopen(url, timeout=timeout) as resp:
        body = json.loads(resp.read().decode('utf-8'))
    return body, int((time.time() - t0) * 1000)


def build_settings(names):
    head = '''# THROWAWAY probe config -- generated by test_engines.py, restored on exit.
use_default_settings:
  engines:
    keep_only:
%s

engines:
%s

server:
  secret_key: "__SECRET__"
  limiter: false
  image_proxy: false

search:
  safe_search: 1
  autocomplete: ""
  formats:
    - html
    - json
  max_page: 1

ui:
  static_use_hash: true

outgoing:
  # Short, because this is a bulk reachability sweep, not a production setting.
  request_timeout: 6.0
  max_request_timeout: 8.0
'''
    keep = '\n'.join('      - %s' % n for n in names)
    blocks = []
    for n in names:
        blocks.append(
            '  - name: %s\n'
            '    disabled: false\n'
            '    # force everything into one category so a single plain query\n'
            '    # fires the whole candidate list at once\n'
            '    categories: [general]\n'
            '    timeout: 6.0\n' % n
        )
    return head % (keep, '\n'.join(blocks))


def main():
    # Read the real secret out of the live settings so the probe instance uses
    # the same one (the placeholder is otherwise harmless for a local probe).
    live = open(SETTINGS, encoding='utf-8').read()

    names_all = image_engine_names()
    valid, unknown = [], []
    for n in CANDIDATES:
        (valid if n in names_all else unknown).append(n)

    print('=' * 72)
    print('ENGINE HUNT -- stage 2: let SearXNG test them itself')
    print('=' * 72)
    print('candidates   : %d' % len(CANDIDATES))
    print('known to image: %d' % len(valid))
    if unknown:
        print('NOT IN IMAGE : %s' % ', '.join(unknown))
    print()

    shutil.copy2(SETTINGS, BACKUP)
    probe = build_settings(valid)
    m = re.search(r'^  secret_key: (.*)$', live, re.M)
    if m:
        probe = probe.replace('__SECRET__', m.group(1).strip().strip('"'))

    try:
        with open(SETTINGS, 'w', encoding='utf-8', newline='\n') as f:
            f.write(probe)

        print('--> recreating container (SearXNG only reads settings at boot)')
        out = run(['docker', 'compose', '-f', COMPOSE, 'up', '-d', '--force-recreate'],
                  cwd=DEPLOY)
        if out.returncode != 0:
            print(out.stdout[-2000:])
            print(out.stderr[-2000:])
            sys.exit('compose failed -- a keep_only name is probably wrong')

        if not wait_ready(time.time() + 60):
            sys.exit('container never became ready; check docker logs searxng')

        print('--> container up, container logs:')
        lg = run(['docker', 'logs', '--tail', '25', 'searxng'], merge=True)
        for line in (lg.stdout or '').split('\n'):
            if line.strip():
                print('    ' + line[:160])
        print()

        total = {}
        reasons = {}
        for i, q in enumerate(QUERIES, 1):
            print('--- query #%d: %s' % (i, q))
            try:
                body, ms = query(q)
            except Exception as exc:
                print('    REQUEST FAILED: %s: %s' % (type(exc).__name__, exc))
                continue
            results = body.get('results', [])
            unresp = body.get('unresponsive_engines', [])
            print('    %d results in %d ms' % (len(results), ms))

            counts = {}
            for r in results:
                for e in r.get('engines', []) or ['?']:
                    counts[e] = counts.get(e, 0) + 1
            for eng, c in sorted(counts.items(), key=lambda kv: -kv[1]):
                total[eng] = max(total.get(eng, 0), c)
            print('    engines that answered: %s'
                  % (', '.join('%s(%d)' % (k, v) for k, v in
                               sorted(counts.items(), key=lambda kv: -kv[1]))
                     or '(none)'))
            for pair in unresp:
                # SearXNG emits ["engine-name", "reason"]
                if isinstance(pair, (list, tuple)) and len(pair) == 2:
                    reasons[pair[0]] = pair[1]
                else:
                    reasons[str(pair)] = '?'
            print('    unresponsive: %s' % (json.dumps(unresp, ensure_ascii=False)
                                            if unresp else '(none reported)'))
            print()

        print('=' * 72)
        print('SUMMARY -- engines that actually returned results')
        print('=' * 72)
        if total:
            for eng, c in sorted(total.items(), key=lambda kv: -kv[1]):
                print('  %-22s %d results' % (eng, c))
        else:
            print('  NONE. Every candidate failed on this network.')
        print()
        print('failure reasons reported by SearXNG:')
        if reasons:
            for eng, why in sorted(reasons.items()):
                print('  %-22s %s' % (eng, why))
        else:
            print('  (none)')
        print()
        silent = [n for n in valid
                  if n not in total and n not in reasons]
        if silent:
            print('silent (no results AND no error -- the 360search failure mode):')
            print('  %s' % ', '.join(silent))
    finally:
        print()
        print('--> restoring the real settings.yml')
        shutil.move(BACKUP, SETTINGS)
        out = run(['docker', 'compose', '-f', COMPOSE, 'up', '-d', '--force-recreate'],
                  cwd=DEPLOY)
        if out.returncode == 0:
            wait_ready(time.time() + 60)
            print('--> deployment restored and running')
        else:
            print('!! restore recreate failed, run-local.ps1 -ForceSettings will fix it')


if __name__ == '__main__':
    main()
