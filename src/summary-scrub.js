/**
 * 摘要身份档案清洗（summary identity scrubber）
 *
 * 起因（2026-10-17）：用户听到 soyo 被问「你是谁」时答
 * 「长崎素世 / 月之森二年级的 / ……怎么突然问这个」，
 * 说"有一种别人告诉我某人是谁的感觉"。
 *
 * 根因不是她乱说。index.js 两处 summaryLimit: 2 ⇒ 每轮注入最近 2 条摘要，
 * 而这些摘要长期写着第三人称的自我档案：
 *   Bot为《BanG Dream!》长崎素世人设(QQ…，生日5月27日…)。
 *   …确认 AI 扮演的长崎素世身份，素世自述为月之森高中部二年级、MyGO!!!!! 贝斯手。
 *   …助手自认千早爱音：粉发浅灰瞳双马尾，16岁，羽丘女子高中一年A班…
 * 于是每轮提示词里都有一段"别人告诉她她是谁"，她照着念。
 *
 * 做法：**注入侧清洗**，DB 原文一个字不动（可回滚）。两处调用：
 *   1. prompt.js 拼【历史摘要】时      → 隔离存量污染
 *   2. ai.js summarize() 喂 previousSummaries 时 → 阻断"旧摘要污染新摘要"的传染
 * 另有 ai.js 摘要提示词加「身份禁区」，让新摘要不再产生这类内容。
 *
 * 设计原则：**宁可漏洗，不可误删**。只清"以助手/Bot 自身为主体"的身份档案，
 * 绝不碰"用户/某群友说了什么"这类真实事件。
 */

// 顺序有依赖：先删整句，再去掉「AI扮演的」这类修饰词，最后处理紧跟人名的身份括号。
const IDENTITY_RULES = [
    // 「Bot为《…》xxx人设(…)。」—— soyo 群聊摘要的开头，8 条全部命中
    [/Bot\s*为[^。；\n]{0,80}?人设[（(][^）)\n]{0,320}[）)]。/g, ''],
    // 同上但没带括号
    [/Bot\s*为[^。；\n]{0,80}?人设。/g, ''],
    // 「助手自认千早爱音：粉发浅灰瞳双马尾，16岁，…能联网。」—— anon 私聊摘要
    [/助手自认[^：:。\n]{0,24}[：:][^。\n]{0,420}。/g, ''],
    // 「助手（自称爱音，MyGO!!!!!吉他手）」—— anon 群聊摘要
    [/助手[（(]自称[^）)\n]{0,90}[）)]/g, '助手'],
    // 「AI扮演的」修饰词（「确认AI扮演的长崎素世身份」→「确认长崎素世身份」）
    [/AI\s*扮演的/g, ''],
    // 紧跟人名的身份括号（「长崎素世（月之森高二、MyGO!!!!!贝斯手）」→「长崎素世」）
    [/(长崎素世|千早爱音|素世|爱音)[（(][^）)\n]{0,12}(月之森|羽丘|MyGO)[^）)\n]{0,60}[）)]/g, '$1'],
    // 「素世自述为月之森高中部二年级、MyGO!!!!!贝斯手。」整句
    [/(?:素世|爱音|助手|Bot|bot)自述为[^。\n]{0,90}。/g, ''],
    // >>> summary-meta-scrub patch >>>
    // 「运行元信息」：谁知道自己在被谁怎么跑，都不该进记忆。
    // 实证（2026-10-18）：soyo 14 条摘要洗完仍有 8 条带着
    //   「werwer自认调教角色卡、开关在手」⇒ 每轮注入 2 条，大概率命中
    //   ⇒ 她会说「服务器都是你在管」。
    //
    // ⚠ 「调教」不能一刀切：小摸自称「被调教过的喵」是真实对话，必须保留。
    //   所以只认「有开关在手」的那一小句，以及「角色卡」（这个词只在技术讨论里出现）。
    [/[^；。\n]{0,12}自认[^；。\n]{0,70}?(?:开关在手|开关在其手里|开关在[^，。；\n]{0,8}手里)[，,；;]?/g, ''],
    [/[^；。\n]{0,26}角色卡[^；。\n]{0,200}[；。]/g, '']
    // <<< summary-meta-scrub patch <<<
];

// 洗完后仍然出现这些串 ⇒ 还有残留（给日志和 verify 脚本用）
// >>> summary-meta-scrub patch >>>
const DOSSIER_MARKERS = ['人设(', '人设（', '助手自认', 'AI扮演的', 'AI 扮演的', '自述为',
    '角色卡', '开关在手', '开关在其手里'];
// <<< summary-meta-scrub patch <<<

export function scrubSummaryIdentity(text = '') {
    let out = String(text || '');
    if (!out) {
        return '';
    }
    for (const [pattern, replacement] of IDENTITY_RULES) {
        out = out.replace(pattern, replacement);
    }
    // 删句后可能留下悬空的顿号或重复句号，收一下（只动标点，不动文字）
    out = out.replace(/[，、]\s*(?=[。；])/g, '');
    out = out.replace(/。{2,}/g, '。');
    return out.trim();
}

export function hasIdentityDossier(text = '') {
    const out = String(text || '');
    return DOSSIER_MARKERS.some((marker) => out.includes(marker));
}
